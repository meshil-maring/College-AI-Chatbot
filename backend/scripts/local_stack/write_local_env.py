"""Write backend/.env.local from the running local Supabase stack.

Usage (from the repository root, after `supabase start`):

    python backend/scripts/local_stack/write_local_env.py

Then run backend commands with BACKEND_ENV=local, for example
`BACKEND_ENV=local .venv/Scripts/python -m pytest` from backend/. `.env` (live)
is never modified; `.env.local` only overrides the database connection and
turns off services that would otherwise reach live resources.
"""

import json
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlparse

BACKEND = Path(__file__).resolve().parents[2]
TARGET = BACKEND / ".env.local"


def local_status() -> dict:
    result = subprocess.run(
        ["supabase", "status", "-o", "json"],
        cwd=BACKEND.parent, capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        sys.exit("Local Supabase is not running. Start it with `supabase start`.")
    # The CLI may print update notices around the JSON document.
    text = result.stdout
    return json.loads(text[text.index("{"): text.rindex("}") + 1])


def render(status: dict) -> str:
    api = status["API_URL"].rstrip("/")
    if urlparse(api).hostname not in {"127.0.0.1", "localhost"}:
        sys.exit(f"Refusing to write a non-local API URL: {api}")
    return "\n".join([
        "# Generated by scripts/local_stack/write_local_env.py. Used only with BACKEND_ENV=local.",
        "ENVIRONMENT=development",
        f"SUPABASE_URL={api}",
        f"SUPABASE_PUBLISHABLE_KEY={status['PUBLISHABLE_KEY']}",
        f"SUPABASE_SECRET_KEY={status['SECRET_KEY']}",
        f"SUPABASE_JWKS_URL={api}/auth/v1/.well-known/jwks.json",
        f"SUPABASE_JWT_ISSUER={api}/auth/v1",
        "# Keep local runs away from live storage and real email delivery.",
        "R2_ENDPOINT_URL=",
        "R2_ACCESS_KEY_ID=",
        "R2_SECRET_ACCESS_KEY=",
        "EMAIL_PROVIDER=local",
        "EMAIL_ALLOW_LIVE_IN_DEVELOPMENT=false",
        "",
    ])


if __name__ == "__main__":
    TARGET.write_text(render(local_status()), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(BACKEND.parent)} for the local stack.")
