"""Generate the frontend's typed policy snapshot from the backend catalog.

Run from backend: uv run python scripts/generate_frontend_rbac.py [--check]
This reads source constants only; it does not load settings or contact a database.
"""

from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "frontend/src/features/auth/rbacPolicy.generated.ts"


def render_policy() -> str:
    catalog = runpy.run_path(str(ROOT / "backend/app/core/permissions.py"))
    security = ast.parse((ROOT / "backend/app/core/security.py").read_text(encoding="utf-8"))
    roles = next(
        ast.literal_eval(node.value)
        for node in security.body
        if isinstance(node, ast.AnnAssign)
        and isinstance(node.target, ast.Name)
        and node.target.id == "SUPPORTED_ROLES"
    )
    codes = catalog["PERMISSIONS"]
    defaults = catalog["DEFAULT_ROLE_PERMISSIONS"]
    assert len(codes) == len(set(codes)), "Duplicate permission codes"
    assert all(set(defaults[role]).issubset(codes) for role in roles)
    lines = [
        "// Generated by backend/scripts/generate_frontend_rbac.py. Do not edit.",
        "// Bootstrap defaults are a reference, not the current user's authorization.",
        "import type { AuthRole } from '../../types/auth.ts'",
        "",
        "export const PERMISSION_CODES = [",
        *(f"  {json.dumps(code)}," for code in codes),
        "] as const",
        "",
        "export type PermissionCode = typeof PERMISSION_CODES[number]",
        "",
        "export const ROLE_DEFAULT_PERMISSIONS = {",
    ]
    for role in roles:
        lines.append(f"  {role}: [")
        lines.extend(f"    {json.dumps(code)}," for code in codes if code in defaults[role])
        lines.append("  ],")
    lines.extend([
        "} as const satisfies Readonly<Record<AuthRole, readonly PermissionCode[]>>",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in snapshot is stale")
    args = parser.parse_args()
    expected = render_policy()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            print("Frontend RBAC snapshot is stale. Run this script without --check.")
            return 1
        print("Frontend RBAC snapshot matches the backend catalog.")
        return 0
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print("Generated frontend/src/features/auth/rbacPolicy.generated.ts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
