"""Build student directory SQL from its maintained sources; never execute SQL."""

from __future__ import annotations

import argparse
import json
import re
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "supabase/migration_sources/student_directory"
GENERATED = "-- GENERATED by scripts/maintenance/student_directory/build_migration.py"


def render_migration(version: str, name: str, files: list[str]) -> tuple[Path, str]:
    if not re.fullmatch(r"\d{14}", version) or not re.fullmatch(r"[a-z][a-z_]+", name):
        raise ValueError("Invalid migration version/name")
    target = ROOT / f"supabase/migrations/{version}_{name}.sql"
    conflicts = [
        path.name for path in target.parent.glob(f"{version}_*.sql") if path != target
    ]
    if conflicts:
        raise ValueError(
            f"Migration version {version} is already used by: {', '.join(conflicts)}"
        )
    parts = [
        GENERATED,
        "-- Edit maintained student_directory sources; retain all earlier migrations.",
        "BEGIN;",
    ]
    for relative in files:
        path = (SOURCE / relative).resolve()
        if not path.is_relative_to(SOURCE.resolve()) or path.suffix != ".sql":
            raise ValueError("SQL sources must stay in the student directory feature")
        content = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if len(content.splitlines()) > 250 or re.search(
            r"^(?:BEGIN|COMMIT|ROLLBACK);\s*$", content, re.MULTILINE
        ):
            raise ValueError(f"Invalid SQL source: {relative}")
        parts.extend(
            [
                f"\n-- SOURCE {relative} sha256={sha256(content.encode()).hexdigest()}",
                content.rstrip(),
            ]
        )
    parts.extend(["COMMIT;", ""])
    return target, "\n".join(parts)


def render() -> list[tuple[Path, str]]:
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    migrations = [
        render_migration(manifest["version"], manifest["name"], manifest["files"])
    ]
    follow_up = manifest.get("follow_up")
    if follow_up:
        migrations.append(
            render_migration(
                follow_up["version"], follow_up["name"], follow_up["files"]
            )
        )
    return migrations


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    migrations = render()
    if args.check:
        stale = [
            target.name
            for target, expected in migrations
            if not target.exists() or target.read_text(encoding="utf-8") != expected
        ]
        if stale:
            print(f"Student directory migrations are stale: {', '.join(stale)}")
            return 1
        print("Student directory migrations match maintained sources.")
        return 0
    for target, expected in migrations:
        if target.exists() and not target.read_text(encoding="utf-8").startswith(
            GENERATED
        ):
            raise ValueError("Refusing to overwrite a handwritten/applied migration")
        target.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {target.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
