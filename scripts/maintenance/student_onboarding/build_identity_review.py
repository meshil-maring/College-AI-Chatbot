"""Build the student identity review migration from its maintained SQL source."""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "supabase/migration_sources/student_identity_review"
GENERATED = "-- GENERATED by scripts/maintenance/student_onboarding/build_identity_review.py"


def render() -> tuple[Path, str]:
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    version, name, files = (manifest[key] for key in ("version", "name", "files"))
    if not re.fullmatch(r"\d{14}", version) or not re.fullmatch(r"[a-z][a-z_]+", name):
        raise ValueError("Invalid migration version/name")
    target = ROOT / f"supabase/migrations/{version}_{name}.sql"
    conflicts = [path.name for path in target.parent.glob(f"{version}_*.sql") if path != target]
    if conflicts:
        raise ValueError(f"Migration version {version} is already used by: {', '.join(conflicts)}")
    if files != ["review.sql"]:
        raise ValueError("Identity review migration source order must be review.sql")
    source = (SOURCE / "review.sql").resolve()
    if not source.is_relative_to(SOURCE.resolve()):
        raise ValueError("SQL source must stay in the identity review feature")
    content = source.read_text(encoding="utf-8").replace("\r\n", "\n")
    if len(content.splitlines()) > 250 or re.search(
        r"^(?:BEGIN|COMMIT|ROLLBACK);\s*$", content, re.MULTILINE
    ):
        raise ValueError("SQL source exceeds limits or contains an outer transaction")
    parts = [
        GENERATED,
        "-- Edit maintained student_identity_review sources; retain all earlier migrations.",
        "BEGIN;",
        f"\n-- SOURCE review.sql sha256={sha256(content.encode()).hexdigest()}",
        content.rstrip(),
        "COMMIT;",
        "",
    ]
    return target, "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target, expected = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            print("Student identity review migration is stale; run its generator.")
            return 1
        print("Student identity review migration matches maintained sources.")
        return 0
    if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED):
        raise ValueError("Refusing to overwrite a handwritten/applied migration")
    target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {target.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
