"""Generate the authorized history-citation reader without connecting to a database."""

import argparse
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[3]
HEADER = '-- GENERATED by scripts/maintenance/migrations/build_history_citations.py'


def render():
    renderer = runpy.run_path(str(Path(__file__).with_name('build_knowledge_revisions.py')))['render']
    return renderer(source=ROOT / 'supabase/migration_sources/history_citations', header=HEADER)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target, content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit('History citation migration is stale; run its generator.')
        print('History citation migration matches maintained sources.')
    else:
        if target.exists() and not target.read_text(encoding='utf-8').startswith(HEADER):
            raise ValueError('Refusing to overwrite a handwritten migration')
        target.write_text(content, encoding='utf-8', newline='\n')
        print(f'Generated {target.relative_to(ROOT).as_posix()}')


if __name__ == '__main__':
    main()
