"""Generate the audience/revision schema migration; never connect to a database."""

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "supabase/migration_sources/knowledge_revisions"
HEADER = "-- GENERATED by scripts/maintenance/migrations/build_knowledge_revisions.py"


def render(*, source=None, header=None):
    source = SOURCE if source is None else source
    header = HEADER if header is None else header
    manifest = json.loads((source / "manifest.json").read_text(encoding="utf-8"))
    version, name, files = (manifest[key] for key in ("version", "name", "files"))
    if not re.fullmatch(r"\d{14}", version) or not re.fullmatch(r"[a-z][a-z_]+", name):
        raise ValueError("Invalid migration version/name")
    if not isinstance(files, list) or not files or len(set(files)) != len(files):
        raise ValueError("SQL source order must be explicit and unique")
    for folder in [source, *(path for path in source.rglob("*") if path.is_dir())]:
        if sum(path.is_file() for path in folder.iterdir()) > 15:
            raise ValueError(f"Source folder exceeds 15 files: {folder.relative_to(ROOT)}")
    parts = [header, f"-- Edit maintained {source.name} sources.", "BEGIN;"]
    for name in files:
        path = (source / name).resolve()
        if not path.is_relative_to(source.resolve()) or path.suffix != ".sql":
            raise ValueError(f"SQL sources must stay within {source.name}")
        content = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if len(content.splitlines()) > 250:
            raise ValueError(f"Source exceeds 250 lines: {name}")
        if re.search(r"^(?:BEGIN|COMMIT|ROLLBACK);\s*$", content, re.MULTILINE):
            raise ValueError("Sources must not contain outer transactions")
        parts.extend([
            f"-- SOURCE {name} sha256={sha256(content.encode()).hexdigest()}",
            content.rstrip(),
        ])
    parts.extend(["NOTIFY pgrst, 'reload schema';", "COMMIT;", ""])
    target = ROOT / f"supabase/migrations/{manifest['version']}_{manifest['name']}.sql"
    return target, "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target, content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Knowledge revision migration is stale; run its generator.")
        print("Knowledge revision migration matches maintained sources.")
        return
    if target.exists() and not target.read_text(encoding="utf-8").startswith(HEADER):
        raise ValueError("Refusing to overwrite a handwritten migration")
    target.write_text(content, encoding="utf-8", newline="\n")
    print(f"Generated {target.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
