"""Build additive department deletion SQL from bounded source; never execute SQL."""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "supabase/migration_sources/department_deletion"
GENERATED = "-- GENERATED by scripts/maintenance/migrations/build_department_deletion.py"


def render() -> tuple[Path, str]:
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    version, name, files = (manifest[key] for key in ("version", "name", "files"))
    if not re.fullmatch(r"\d{14}", version) or not re.fullmatch(r"[a-z][a-z_]+", name):
        raise ValueError("Invalid migration version/name")
    target = ROOT / f"supabase/migrations/{version}_{name}.sql"
    conflicts = [path.name for path in target.parent.glob(f"{version}_*.sql") if path != target]
    if conflicts:
        raise ValueError(f"Migration version {version} is already used by: {', '.join(conflicts)}")
    if not isinstance(files, list) or not files or len(set(files)) != len(files):
        raise ValueError("SQL source order must be explicit and unique")
    for folder in [SOURCE, *(path for path in SOURCE.rglob("*") if path.is_dir())]:
        if sum(path.is_file() for path in folder.iterdir()) > 15:
            raise ValueError(f"Source folder exceeds 15 files: {folder.relative_to(ROOT)}")
    parts = [GENERATED, "-- Edit maintained department_deletion sources; retain all earlier migrations.", "BEGIN;"]
    for relative in files:
        path = (SOURCE / relative).resolve()
        if not path.is_relative_to(SOURCE.resolve()) or path.suffix != ".sql":
            raise ValueError("SQL sources must stay in the department deletion feature")
        content = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if len(content.splitlines()) > 250:
            raise ValueError(f"SQL source exceeds 250 lines: {relative}")
        if re.search(r"^(?:BEGIN|COMMIT|ROLLBACK);\s*$", content, re.MULTILINE):
            raise ValueError("Source files must not contain outer transactions")
        parts.extend([f"\n-- SOURCE {relative} sha256={sha256(content.encode()).hexdigest()}", content.rstrip()])
    parts.extend(["COMMIT;", ""])
    return target, "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target, expected = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            print("Department deletion migration is stale; run its generator.")
            return 1
        print("Department deletion migration matches maintained sources.")
        return 0
    if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED):
        raise ValueError("Refusing to overwrite a handwritten/applied migration")
    target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {target.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
