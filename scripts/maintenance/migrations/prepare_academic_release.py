"""Render a pinned academic schema release; this tool never connects to a database."""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import subprocess
import sys
from uuid import UUID

ROOT = Path(__file__).resolve().parents[3]
VERSION = "20261021000000"
NAME = "academic_curriculum_packages"
ABSENT_UNRELATED = {"20261017000000", "20261019000000"}


def render(preflight: Path, *, commit: bool = False) -> str:
    evidence = json.loads(preflight.read_text(encoding="utf-8-sig"))["rows"][0]["preflight"]
    institutions = evidence["institutions"]
    if len(institutions) != 1:
        raise ValueError("This release requires one explicitly resolved institution")
    institution = institutions[0]
    institution_id, code = str(UUID(institution["institution_id"])), institution["code"]
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", code):
        raise ValueError("Unexpected institution code")
    if evidence["named_curricula"] is not None or evidence["academic_classes"] is not None:
        raise ValueError("Foundation already present; do not replace applied source")
    installed = sorted(evidence["migrations"])
    local = {p.name.split("_", 1)[0] for p in (ROOT / "supabase/migrations").glob("*.sql")}
    if set(installed) != local - ABSENT_UNRELATED - {VERSION}:
        raise ValueError("Live prerequisite ledger differs from the reviewed academic baseline")
    source = ROOT / f"supabase/migrations/{VERSION}_{NAME}.sql"
    content = source.read_text(encoding="utf-8")
    if not content.startswith("-- GENERATED by scripts/maintenance/migrations/build_academic_packages.py"):
        raise ValueError("Unrecognized migration source")
    if not content.endswith("COMMIT;\n") or content.count("\nBEGIN;\n") != 1:
        raise ValueError("Migration transaction wrapper changed")
    body = content.split("\nBEGIN;\n", 1)[1].removesuffix("COMMIT;\n")
    delimiter = "$academic_release_source$"
    if delimiter in body:
        raise ValueError("Release ledger delimiter collides with source")
    digest = sha256(content.encode()).hexdigest()
    ledger = ",".join(f"'{version}'" for version in installed)
    guard = f"""BEGIN;
SET LOCAL lock_timeout = '8s';
SET LOCAL statement_timeout = '90s';
DO $release_guard$
BEGIN
    IF current_user <> 'postgres' OR NOT EXISTS (SELECT 1 FROM public.institutions
        WHERE institution_id = '{institution_id}' AND code = '{code}' AND status = 'active') THEN
        RAISE EXCEPTION 'Pinned institution and database-owner access required';
    END IF;
    IF (SELECT array_agg(version ORDER BY version) FROM supabase_migrations.schema_migrations)
        IS DISTINCT FROM ARRAY[{ledger}]::text[] THEN
        RAISE EXCEPTION 'Migration ledger changed since reviewed preflight';
    END IF;
    IF to_regclass('public.academic_curricula') IS NOT NULL
        OR to_regclass('public.academic_classes') IS NOT NULL THEN
        RAISE EXCEPTION 'Academic foundation already exists';
    END IF;
END;
$release_guard$;
"""
    ledger_write = f"""
INSERT INTO supabase_migrations.schema_migrations(version, name, statements)
VALUES ('{VERSION}', '{NAME}', ARRAY[{delimiter}{body}{delimiter}]);
SELECT jsonb_build_object('version','{VERSION}', 'source_sha256','{digest}',
    'rehearsal',{str(not commit).lower()},
    'academic_tables',(SELECT count(*) FROM pg_tables WHERE schemaname = 'public'
        AND tablename IN ('academic_curricula','academic_curriculum_subjects','academic_subject_packages',
            'academic_package_subjects','academic_classes','academic_class_packages','academic_class_subjects',
            'academic_class_responsibilities','academic_class_placements','academic_package_assignments',
            'academic_package_revisions','academic_subject_participation','academic_package_requests')),
    'prepare_rpc_present',to_regprocedure('public.academic_package_prepare_teaching(uuid,uuid,uuid)') IS NOT NULL
) AS academic_schema_release;
{'COMMIT' if commit else 'ROLLBACK'};
"""
    return f"-- Generated reviewed release, source sha256={digest}\n{guard}{body}{ledger_write}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preflight", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--commit", action="store_true")
    args = parser.parse_args()
    subprocess.run([sys.executable, str(ROOT / "scripts/maintenance/migrations/build_academic_packages.py"),
                    "--check"], check=True)
    content = render(args.preflight, commit=args.commit)
    args.output.write_text(content, encoding="utf-8")
    print(f"Prepared {'COMMIT' if args.commit else 'ROLLBACK'} schema release: {args.output}")


if __name__ == "__main__":
    main()
