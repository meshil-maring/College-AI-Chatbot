"""Assemble focused academic SQL sources into one deterministic migration."""

from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "supabase/migration_sources/academic_packages"
GENERATED = "-- GENERATED by scripts/maintenance/migrations/build_academic_packages.py"


def render() -> tuple[Path, str]:
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    version, name, files = (manifest[key] for key in ("version", "name", "files"))
    if not isinstance(version, str) or not re.fullmatch(r"\d{14}", version):
        raise ValueError("Migration version must contain exactly 14 digits")
    if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z_]+", name):
        raise ValueError("Migration name must use lowercase words")
    if not isinstance(files, list) or not files or len(set(files)) != len(files):
        raise ValueError("Manifest must list unique ordered SQL fragments")
    for folder in [SOURCE, *(p for p in SOURCE.rglob("*") if p.is_dir())]:
        if sum(p.is_file() for p in folder.iterdir()) > 15:
            raise ValueError(f"Source folder exceeds 15 files: {folder.relative_to(ROOT)}")
    parts = [GENERATED, "-- Edit the manifest and focused source fragments; do not edit this output.", "BEGIN;"]
    for relative in files:
        if not isinstance(relative, str):
            raise ValueError("Manifest file entries must be strings")
        path = (SOURCE / relative).resolve()
        if not path.is_relative_to(SOURCE.resolve()) or path.suffix != ".sql":
            raise ValueError("SQL fragment must stay inside academic_packages sources")
        content = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if len(content.splitlines()) > 250:
            raise ValueError(f"SQL fragment exceeds 250 lines: {relative}")
        if re.search(r"^(?:BEGIN|COMMIT|ROLLBACK);\s*$", content, re.MULTILINE):
            raise ValueError(f"Outer transactions belong to the generator: {relative}")
        digest = sha256(content.encode("utf-8")).hexdigest()
        parts.extend([f"\n-- SOURCE {relative} sha256={digest}", content.rstrip()])
    parts.extend(["\nNOTIFY pgrst, 'reload schema';", "COMMIT;", ""])
    return ROOT / f"supabase/migrations/{version}_{name}.sql", "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated migration without changing it")
    args = parser.parse_args()
    target, expected = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            print("Academic package migration is missing or stale; run the generator.")
            return 1
        print("Generated academic package migration matches focused sources.")
        return 0
    if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED):
        raise ValueError("Refusing to overwrite an existing handwritten migration")
    target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {target.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
